/**
 * CNC drill toolpaths: peck drilling at the center of every closed shape.
 *
 * LunarTPP (the toolpath engine) has no drilling mode, so drill toolpaths are generated
 * here and written in the engine's toolpath JSON format. Downstream G-code generation
 * consumes them unchanged.
 */
import fs from 'fs';

import SVGParser, { flip, rotate, scale } from '../../../shared/lib/SVGParser';

const DUPLICATE_TOLERANCE = 0.01; // mm

const distance = (a, b) => Math.hypot(a.x - b.x, a.y - b.y);

/**
 * Transform the SVG like CncToolPathGenerator._processSVG and return the bounding box
 * center of each closed, visible path, relative to the model center (mm, Y up).
 */
export function getDrillPoints(svg, modelInfo) {
    const { sourceType, transformation } = modelInfo;
    const { scaleX, scaleY, rotationZ } = transformation;

    if (sourceType !== 'dxf') {
        flip(svg, 1);
    }
    scale(svg, {
        x: (scaleX > 0 ? 1 : -1) * transformation.width / svg.width,
        y: (scaleY > 0 ? 1 : -1) * transformation.height / svg.height
    });
    rotate(svg, rotationZ);

    const centerX = svg.viewBox[0] + svg.viewBox[2] / 2;
    const centerY = svg.viewBox[1] + svg.viewBox[3] / 2;

    const points = [];
    for (const shape of svg.shapes) {
        if (shape.visibility === false) {
            continue;
        }
        for (const path of shape.paths) {
            if (!path.closed || path.points.length === 0) {
                continue;
            }
            const xs = path.points.map(p => p[0]);
            const ys = path.points.map(p => p[1]);
            const point = {
                x: (Math.min(...xs) + Math.max(...xs)) / 2 - centerX,
                y: (Math.min(...ys) + Math.max(...ys)) / 2 - centerY
            };
            if (!points.some(p => distance(p, point) < DUPLICATE_TOLERANCE)) {
                points.push(point);
            }
        }
    }
    return points;
}

/**
 * Nearest-neighbour ordering starting with the first point.
 */
export function orderPoints(points) {
    const remaining = points.slice(1);
    const ordered = points.slice(0, 1);
    while (remaining.length > 0) {
        const last = ordered[ordered.length - 1];
        let nearest = 0;
        for (let i = 1; i < remaining.length; i++) {
            if (distance(last, remaining[i]) < distance(last, remaining[nearest])) {
                nearest = i;
            }
        }
        ordered.push(remaining.splice(nearest, 1)[0]);
    }
    return ordered;
}

const round3 = (n) => Math.round(n * 1000) / 1000;

/**
 * Build engine-format commands that peck-drill each point (points already ordered).
 * Feeds are gcodeConfig keys, substituted by GcodeGenerator.parseAsCNC.
 */
export function buildDrillMoves(points, gcodeConfig) {
    const { targetDepth, stepDown, safetyHeight, stopHeight } = gcodeConfig;
    const depthTarget = round3(targetDepth);
    // Pecks below the 0.001 mm rounding step would never advance the depth
    const peck = stepDown >= 0.001 ? stepDown : depthTarget;
    const retractZ = Math.min(1, safetyHeight);

    const data = [
        { C: '; G-code for CNC drilling' },
        { C: '; Generated by Snapmaker Luban' },
        { G: 90 },
        { G: 21 },
        { G: 0, Z: safetyHeight, F: 'jogSpeed' },
        { M: 3, P: 100 }
    ];
    for (const { x, y } of points) {
        data.push({ G: 0, X: x, Y: y, F: 'jogSpeed' });
        data.push({ G: 0, Z: retractZ });
        let depth = 0;
        while (depth < depthTarget) {
            depth = round3(Math.min(depth + peck, depthTarget));
            data.push({ G: 1, Z: -depth, F: 'plungeSpeed' });
            data.push({ G: 0, Z: retractZ });
        }
        data.push({ G: 0, Z: safetyHeight });
    }
    data.push({ G: 0, Z: stopHeight });
    return data;
}

/**
 * Estimated duration in seconds; speeds are mm/min.
 */
const estimateTime = (data, gcodeConfig) => {
    const { jogSpeed, plungeSpeed } = gcodeConfig;
    let seconds = 0;
    let current = { X: 0, Y: 0, Z: 0 };
    for (const cmd of data) {
        if (cmd.G !== 0 && cmd.G !== 1) {
            continue;
        }
        const next = { ...current, ...('X' in cmd ? { X: cmd.X } : {}), ...('Y' in cmd ? { Y: cmd.Y } : {}), ...('Z' in cmd ? { Z: cmd.Z } : {}) };
        const length = Math.hypot(next.X - current.X, next.Y - current.Y, next.Z - current.Z);
        const speed = cmd.G === 1 ? plungeSpeed : jogSpeed;
        seconds += speed > 0 ? length / speed * 60 : 0;
        current = next;
    }
    return seconds;
};

/**
 * Drill toolpath object in the LunarTPP toolpath JSON format.
 */
export function generateDrillToolPathObj(svg, modelInfo) {
    const { mode, transformation, gcodeConfig } = modelInfo;
    const points = orderPoints(getDrillPoints(svg, modelInfo));
    if (points.length === 0) {
        throw new Error(`Drill: no closed shapes found in ${modelInfo.originalName || modelInfo.uploadName}`);
    }
    const data = buildDrillMoves(points, gcodeConfig);
    const xs = points.map(p => p.x);
    const ys = points.map(p => p.y);

    return {
        from: 'LubanJS-Drill',
        headType: 'cnc',
        mode,
        isRotate: false,
        diameter: 0,
        positionX: transformation.positionX,
        positionY: transformation.positionY,
        positionZ: transformation.positionZ,
        rotationB: 0,
        estimatedTime: estimateTime(data, gcodeConfig),
        boundingBox: {
            min: { x: Math.min(...xs), y: Math.min(...ys), z: -gcodeConfig.targetDepth, b: 0 },
            max: { x: Math.max(...xs), y: Math.max(...ys), z: Math.max(gcodeConfig.safetyHeight, gcodeConfig.stopHeight), b: 0 }
        },
        data
    };
}

/**
 * Generate and write one drill toolpath file per model. Resolves the toolpath file names.
 */
export async function generateDrillToolPathFiles(modelInfos) {
    const filenames = [];
    for (const modelInfo of modelInfos) {
        if (modelInfo.materials?.isRotate) {
            throw new Error('Drill: rotary mode is not supported');
        }
        const svg = await new SVGParser().parseFile(`${process.env.Tmpdir}/${modelInfo.uploadName}`);
        const toolPathObj = generateDrillToolPathObj(svg, modelInfo);
        fs.writeFileSync(`${process.env.Tmpdir}/${modelInfo.toolpathFileName}`, JSON.stringify(toolPathObj));
        filenames.push(modelInfo.toolpathFileName);
    }
    return filenames;
}

const VIEW_PATH_DENSITY = 10; // cells per mm, as in CncToolPathGenerator

/**
 * Preview height map in the CncToolPathGenerator view path format: a tool-sized disc
 * at target depth at each drill point, untouched material elsewhere.
 */
export function generateDrillViewPathObj(svg, modelInfo) {
    const { sourceType, mode, transformation, gcodeConfig, toolParams } = modelInfo;
    const { targetDepth } = gcodeConfig;
    const { positionX, positionY, positionZ } = transformation;
    const points = getDrillPoints(svg, modelInfo);

    const width = Math.round(Math.abs(svg.viewBox[2]) * VIEW_PATH_DENSITY);
    const height = Math.round(Math.abs(svg.viewBox[3]) * VIEW_PATH_DENSITY);
    const radius = toolParams.toolDiameter / 2;

    const data = [];
    for (let j = 0; j <= height; j++) {
        data.push([]);
        for (let i = 0; i <= width; i++) {
            data[j][i] = { x: (i - width / 2) / VIEW_PATH_DENSITY, y: 0 };
        }
    }
    // Stamp a disc around each hole, only visiting the cells of its bounding square
    for (const p of points) {
        const ci = Math.round(p.x * VIEW_PATH_DENSITY + width / 2);
        const cj = Math.round(p.y * VIEW_PATH_DENSITY + height / 2);
        const r = Math.ceil(radius * VIEW_PATH_DENSITY);
        for (let j = Math.max(0, cj - r); j <= Math.min(height, cj + r); j++) {
            for (let i = Math.max(0, ci - r); i <= Math.min(width, ci + r); i++) {
                const x = (i - width / 2) / VIEW_PATH_DENSITY;
                const y = (j - height / 2) / VIEW_PATH_DENSITY;
                if (Math.hypot(p.x - x, p.y - y) <= radius) {
                    data[j][i].y = -targetDepth;
                }
            }
        }
    }
    data.reverse();

    return {
        sourceType,
        mode,
        width: width / VIEW_PATH_DENSITY,
        height: height / VIEW_PATH_DENSITY,
        positionX,
        positionY,
        positionZ,
        rotationB: 0,
        targetDepth,
        boundingBox: {
            min: { x: positionX - width / 2 / VIEW_PATH_DENSITY, y: positionY - height / 2 / VIEW_PATH_DENSITY, z: -targetDepth },
            max: { x: positionX + width / 2 / VIEW_PATH_DENSITY, y: positionY + height / 2 / VIEW_PATH_DENSITY, z: 0 },
            length: { x: width / VIEW_PATH_DENSITY, y: height / VIEW_PATH_DENSITY, z: targetDepth }
        },
        isRotate: false,
        diameter: 0,
        data
    };
}
